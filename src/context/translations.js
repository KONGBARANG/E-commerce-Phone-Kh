export function translateText(value, language) {
  if (language === 'km') return value;
  const trimmed = value.trim();
  const translated = translations[trimmed.replace(/\s+/g, ' ')];
  if (translated) return value.replace(trimmed, translated);

  const dynamicPatterns = [
    [/^លទ្ធផលសម្រាប់ “(.*)”$/, 'Results for “$1”'],
    [/^(\d+) ប្រភេទផលិតផលក្នុងកន្ត្រករបស់អ្នក$/, '$1 product types in your cart'],
    [/^បង្ហាញ (\d+) ផលិតផល$/, 'Showing $1 products'],
    [/^តម្រង(.*)$/, 'Filter $1'],
    [/^(\d+) គ្រឿង$/, '$1 units'],
    [/^ពណ៌ (.*)$/, 'Color: $1'],
    [/^ចំនួន (\d+)$/, 'Quantity $1'],
    [/^សួស្តី (.*)$/, 'Hello, $1'],
    [/^កូដ (.*) ត្រូវបានអនុវត្តដោយជោគជ័យ។$/, 'Code $1 applied successfully.'],
    [/^រូបភាពផលិតផល (\d+)$/, 'Product image $1'],
    [/^បានជ្រើសរើស៖ (.*)$/, 'Selected: $1'],
    [/^(\d+) មុខ$/, '$1 items'],
    [/^កន្ត្រក (\d+) មុខ$/, 'Cart: $1 items'],
    [/^គណនី (.*)$/, 'Account: $1'],
    [/^ស្វែងរក “(.*)” →$/, 'Search “$1” →'],
    [/^(\d+) ឆ្នាំ$/, '$1 year'],
    [/^ការកុម្ម៉ង់ (.*) ត្រូវបានលុប។$/, 'Order $1 has been deleted.'],
    [/^ការកុម្ម៉ង់ (.*) ត្រូវបានបោះបង់។ សំណើសងប្រាក់ត្រូវបានផ្ញើទៅ Admin។$/, 'Order $1 was cancelled. A refund request was sent to the admin.'],
    [/^ការកុម្ម៉ង់ (.*) ត្រូវបានបោះបង់។$/, 'Order $1 has been cancelled.'],
    [/^បានបញ្ជាក់ថាអ្នកបានទទួលប្រាក់សងវិញសម្រាប់ការកុម្ម៉ង់ (.*)។$/, 'Confirmed that you received the refund for order $1.'],
    [/^បានបញ្ជាក់ថាអ្នកបានទទួលទំនិញពីការកុម្ម៉ង់ (.*)។$/, 'Confirmed that you received the items for order $1.'],
    [/^បានកត់ត្រាថា Admin បានបាញ់ប្រាក់សងសម្រាប់ការកុម្ម៉ង់ (.*)។$/, 'Recorded that the admin sent the refund for order $1.'],
    [/^ការកុម្ម៉ង់ថ្មីពី (.*) \((.*)\)$/, 'New order from $1 ($2)'],
    [/^សារថ្មីពី (.*) \((.*)\)$/, 'New message from $1 ($2)'],
    [/^អតិថិជន (.*) បានឆ្លើយតបសារ$/, 'Customer $1 replied to a message'],
    [/^សារដែលបានផ្ញើតាមទំព័រទំនាក់ទំនង · មិនទាន់អាន (\d+)$/, 'Messages sent through the contact page · $1 unread'],
    [/^មិនទាន់អាន (.*)$/, '$1 unread'],
    [/^បានបញ្ជាក់ការទូទាត់ពី (.*) \((.*)\)$/, 'Payment confirmed by $1 ($2)'],
    [/^អតិថិជនបានបញ្ជាក់ទទួលទំនិញ \((.*)\)$/, 'Customer confirmed receipt for order $1'],
    [/^តើអ្នកប្រាកដថាចង់លុបការកុម្ម៉ង់ COD (.*) មែនទេ\?$/, 'Are you sure you want to delete COD order $1?'],
  ];
  for (const [pattern, replacement] of dynamicPatterns) {
    if (pattern.test(trimmed)) return value.replace(trimmed, trimmed.replace(pattern, replacement));
  }
  return value;
}
